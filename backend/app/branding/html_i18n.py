def _parse_priority(token: str) -> tuple[float, str]:
    """Parse `'hy;q=0.9'` → `(0.9, 'hy')`. Missing q defaults to 1.0."""
    parts = token.strip().split(";")
    locale = parts[0].strip().lower().split("-")[0]  # 'hy-AM' → 'hy'
    q = 1.0
    for p in parts[1:]:
        kv = p.strip().split("=", 1)
        if len(kv) == 2 and kv[0].strip().lower() == "q":
            try:
                q = float(kv[1].strip())
            except ValueError:
                pass
    return q, locale


def pick_locale(accept_language: str | None) -> Locale:
    """Pick the best-supported locale from an `Accept-Language` header.

    Examples::

        pick_locale("hy-AM,hy;q=0.9,en;q=0.7") -> "hy"
        pick_locale("ru;q=0.8,en;q=0.5")        -> "ru"
        pick_locale(None)                        -> "en"
        pick_locale("fr-FR")                     -> "en"  (unsupported → fallback)
    """
    if not accept_language:
        return DEFAULT_LOCALE
    candidates: list[tuple[float, str]] = []
    for token in accept_language.split(","):
        if not token.strip():
            continue
        candidates.append(_parse_priority(token))
    candidates.sort(key=lambda x: -x[0])  # highest q first
    for _, locale in candidates:
        if locale in SUPPORTED:
            return locale  # type: ignore[return-value]
    return DEFAULT_LOCALE


def t(key: str, locale: Locale = DEFAULT_LOCALE, fallback: str | None = None) -> str:
    """Look up a label by `key` for `locale`.

    Order: `INVOICE_LABELS[key][locale]` → `INVOICE_LABELS[key]['en']` →
    `fallback` → `key`. The English fallback ensures unsupported languages or
    missing translations still render readable text.
    """
    entry = INVOICE_LABELS.get(key)
    if entry is None:
        return fallback if fallback is not None else key
    return entry.get(locale) or entry.get("en") or (fallback if fallback is not None else key)


def locales() -> Iterable[Locale]:
    return SUPPORTED
