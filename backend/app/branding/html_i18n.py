"""Server-rendered HTML label translations (T-P4-3).

FastAPI renders branded HTML for invoices, receipts, and statements. Those
docs ship customer-facing strings ("Invoice", "Period", "Balance due", …).
Pre-T-P4-3 every label was hardcoded English; Armenian customers received
English documents.

This module bundles the label dict for the three customer-facing locales
(en / hy / ru) and exposes:
* `pick_locale(accept_language)` — pick a locale from an HTTP `Accept-Language`
  header (or fall back to `en`).
* `t(key, locale, fallback=None)` — synchronous lookup. Misses fall back to
  the English value, or to the explicit `fallback`, or to the key itself.

No DB hit on the render path. The translation table in `routers/i18n.py`
remains the authoritative source for *runtime-tenant-overridable* labels
(admin SPA + studio); HTML rendering uses these bundled values for speed
and decoupling from the admin tenant config.
"""
